import 'dart:typed_data';

import 'package:flutter/material.dart' show Color;
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

final _amount = NumberFormat('#,##,##0.00', 'en_IN');
final _date = DateFormat('dd-MM-yyyy');
final _time = DateFormat('HH:mm');

String _rs(int paise) => _amount.format(paise / 100);

/// Builds a bank-statement style passbook PDF from the /passbook API response.
/// (The built-in PDF font has no ₹ symbol, so amounts are written as "Rs.")
Future<Uint8List> buildPassbookPdf(Map<String, dynamic> data, String bankName, Color brandColor) async {
  final acc = data['account'] as Map<String, dynamic>;
  final cust = data['customer'] as Map<String, dynamic>;
  final entries = (data['entries'] as List).cast<Map<String, dynamic>>();
  final color = PdfColor.fromInt(brandColor.toARGB32());
  final branch = acc['branch'] as Map<String, dynamic>;

  int credits = 0, debits = 0;
  for (final e in entries) {
    if (e['type'] == 'CR') {
      credits += e['amount'] as int;
    } else {
      debits += e['amount'] as int;
    }
  }

  pw.Widget info(String label, String value) => pw.Padding(
        padding: const pw.EdgeInsets.only(bottom: 2),
        child: pw.Row(children: [
          pw.SizedBox(width: 95, child: pw.Text(label, style: const pw.TextStyle(color: PdfColors.grey700))),
          pw.Expanded(child: pw.Text(value, style: pw.TextStyle(fontWeight: pw.FontWeight.bold))),
        ]),
      );

  final doc = pw.Document(title: '$bankName passbook ${acc['account_no']}', author: bankName);
  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    margin: const pw.EdgeInsets.all(28),
    header: (ctx) => pw.Container(
      padding: const pw.EdgeInsets.all(12),
      color: color,
      child: pw.Row(children: [
        pw.Text(bankName, style: pw.TextStyle(color: PdfColors.white, fontSize: 20, fontWeight: pw.FontWeight.bold)),
        pw.Spacer(),
        pw.Text('ACCOUNT STATEMENT', style: const pw.TextStyle(color: PdfColors.white, fontSize: 12)),
      ]),
    ),
    footer: (ctx) => pw.Row(children: [
      pw.Text('Demo statement generated by RakshakPay - fake money only. '
          'Generated ${DateFormat('dd-MM-yyyy HH:mm').format(DateTime.now())}',
          style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
      pw.Spacer(),
      pw.Text('Page ${ctx.pageNumber} of ${ctx.pagesCount}', style: const pw.TextStyle(fontSize: 8)),
    ]),
    build: (ctx) => [
      pw.SizedBox(height: 12),
      pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
        pw.Expanded(
          child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
            info('Name', cust['full_name']),
            info('Customer ID', cust['cif']),
            info('Address', '${cust['address']}, ${cust['city']} - ${cust['pincode']}'),
            info('Mobile', 'XXXXXX${(cust['mobile'] as String).substring(6)}'),
          ]),
        ),
        pw.SizedBox(width: 16),
        pw.Expanded(
          child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
            info('Account No', acc['account_no']),
            info('Account type', acc['account_type'] == 'CURRENT' ? 'Current (Merchant)' : 'Savings'),
            info('Branch', branch['name']),
            info('IFSC', branch['ifsc']),
            info('Status', acc['status']),
          ]),
        ),
      ]),
      pw.SizedBox(height: 12),
      pw.TableHelper.fromTextArray(
        headers: ['Date', 'Narration', 'Ref / UTR', 'Withdrawal (Rs.)', 'Deposit (Rs.)', 'Balance (Rs.)'],
        headerStyle: pw.TextStyle(color: PdfColors.white, fontWeight: pw.FontWeight.bold, fontSize: 9),
        headerDecoration: pw.BoxDecoration(color: color),
        cellStyle: const pw.TextStyle(fontSize: 8),
        cellAlignments: {
          0: pw.Alignment.centerLeft,
          1: pw.Alignment.centerLeft,
          2: pw.Alignment.centerLeft,
          3: pw.Alignment.centerRight,
          4: pw.Alignment.centerRight,
          5: pw.Alignment.centerRight,
        },
        columnWidths: {
          0: const pw.FixedColumnWidth(58),
          1: const pw.FlexColumnWidth(3),
          2: const pw.FixedColumnWidth(70),
          3: const pw.FixedColumnWidth(66),
          4: const pw.FixedColumnWidth(66),
          5: const pw.FixedColumnWidth(70),
        },
        oddRowDecoration: const pw.BoxDecoration(color: PdfColors.grey100),
        data: [
          for (final e in entries)
            [
              '${_date.format(DateTime.parse(e['date']))}\n${_time.format(DateTime.parse(e['date']))}',
              e['narration'],
              e['utr'],
              e['type'] == 'DR' ? _rs(e['amount']) : '',
              e['type'] == 'CR' ? _rs(e['amount']) : '',
              _rs(e['balance_after']),
            ],
        ],
      ),
      pw.SizedBox(height: 12),
      pw.Container(
        padding: const pw.EdgeInsets.all(8),
        decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfColors.grey400)),
        child: pw.Row(children: [
          for (final (label, paise) in [
            ('Total deposits', credits),
            ('Total withdrawals', debits),
            ('On hold', acc['lien_amount'] as int),
            ('Closing balance', acc['balance'] as int),
          ])
            pw.Expanded(
              child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
                pw.Text(label, style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700)),
                pw.Text('Rs. ${_rs(paise)}', style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold)),
              ]),
            ),
        ]),
      ),
    ],
  ));
  return doc.save();
}
